#!/usr/bin/env python3
"""Check saved demo notebooks for sequential execution counts and error outputs.
Nonempty code cells' ``execution_count`` values should form the sequence
1, 2, 3, ... with no gaps, duplicates, or out-of-order numbers.

A non-sequential execution_count indicates the notebook was not saved after
a fresh top-to-bottom run: a cell may have been added, deleted, or re-run
out of order, so the saved outputs may no longer reflect the saved source.
Sequential counts alone cannot prove the source was not edited afterward.
Such discrepancies are cheap to introduce while
iterating (edit one cell, forget to rerun everything below it) and easy to
miss on casual review, since the notebook still looks fine until someone
actually checks the numbers.

Usage:
    python scripts/check_notebook_execution.py [PATH ...] [--strict] [--quiet]
                                                [--diff [REF]]

PATH defaults to every notebook under demos/. ``--diff [REF]`` (REF defaults
to ``develop``) restricts scanning to notebooks that changed relative to
REF -- committed on the branch, modified in the working tree, or untracked.
Informational by default; ``--strict`` turns any finding into a nonzero exit
code, for use in `make check`/CI.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_ref_style import _changed_files, _display_path, _parse_diff_flag, _summary

REPO_ROOT = Path(__file__).resolve().parent.parent
BOOTSTRAP_CELL_MARKER = "# @title Execute this cell to install dependencies"


def _is_generated_bootstrap(cell):
    """Return whether `cell` is the Colab bootstrap generated by this repo."""
    source = cell.get("source", [])
    source = source if isinstance(source, str) else "".join(source)
    return (
        source.startswith(BOOTSTRAP_CELL_MARKER)
        and "import google.colab" in source
        and ("!pip install -q qmcpy" in source
             or "!pip install -q -e {repo_root}" in source)
    )


def check_notebook_file(path):
    """Return a list of (location, category, detail) findings for one notebook."""
    notebook = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(notebook, dict) or not isinstance(notebook.get("cells"), list):
        raise ValueError("notebook must contain a list of cells")
    findings = []
    expected = 0
    for idx, cell in enumerate(notebook["cells"]):
        if not isinstance(cell, dict):
            raise ValueError(f"cell {idx} must be an object")
        if cell.get("cell_type") != "code":
            continue
        source = cell.get("source")
        if "source" in cell and not (
            isinstance(source, str)
            or isinstance(source, list) and all(isinstance(line, str) for line in source)
        ):
            raise ValueError(f"cell {idx} source must be a string or list of strings")
        outputs = cell.get("outputs", [])
        if not isinstance(outputs, list):
            raise ValueError(f"cell {idx} outputs must be a list")
        for output in outputs:
            if not isinstance(output, dict):
                raise ValueError(f"cell {idx} output must be an object")
            if output.get("output_type") == "error":
                ename = output.get("ename", "Error")
                evalue = output.get("evalue", "")
                if not isinstance(ename, str) or not isinstance(evalue, str):
                    raise ValueError(f"cell {idx} error name and value must be strings")
                findings.append((
                    f"cell {idx}", "cell-has-error-output",
                    f"saved output includes {ename}: {evalue[:80]}",
                ))
        # This generated setup cell is intentionally left unexecuted when a
        # notebook is saved locally; it only runs when the notebook opens in
        # Colab, so it is not part of the local execution-count sequence.
        if _is_generated_bootstrap(cell) and cell.get("execution_count") is None:
            continue
        # Jupyter itself never assigns an execution_count to an empty (or
        # whitespace-only) cell during Run All, so it is not part of the
        # sequence either; counting it would misreport every later cell too.
        # A missing "source" key (as opposed to a present-but-empty one) is
        # not a real notebook shape, just a minimal test fixture, so it is
        # not treated as empty here.
        if source is not None:
            source_text = source if isinstance(source, str) else "".join(source)
            if not source_text.strip():
                continue
        expected += 1
        actual = cell.get("execution_count")
        if actual != expected:
            findings.append((
                f"cell {idx}", "execution-count-not-sequential",
                f"execution_count is {actual!r}, expected {expected} "
                "(saved execution counts are not sequential)",
            ))
    return findings


def _iter_notebook_files(root):
    yield from sorted((root / "demos").rglob("*.ipynb"))


def main(argv):
    argv, diff_ref = _parse_diff_flag(list(argv))
    strict = "--strict" in argv
    quiet = "--quiet" in argv
    paths = [a for a in argv if not a.startswith("-")]
    root = REPO_ROOT

    if paths:
        nb_files = []
        for p in map(Path, paths):
            p = p.resolve()
            if p.suffix == ".ipynb":
                nb_files.append(p)
            elif p.is_dir():
                nb_files.extend(sorted(p.rglob("*.ipynb")))
    else:
        nb_files = list(_iter_notebook_files(root))

    if diff_ref is not None:
        try:
            changed = _changed_files(diff_ref)
        except RuntimeError as exc:
            print(f"ERROR: --diff {diff_ref}: {exc}", file=sys.stderr)
            return 1
        else:
            nb_files = [f for f in nb_files if f.resolve() in changed]

    total = 0
    by_cat = {}
    per_file = {}
    for f in nb_files:
        try:
            findings = check_notebook_file(f)
        except (OSError, ValueError) as exc:
            findings = [("file", "invalid-notebook", str(exc))]
        if findings:
            per_file[f] = findings
            for _, cat, _ in findings:
                by_cat[cat] = by_cat.get(cat, 0) + 1
                total += 1

    if total and not quiet:
        print()
        for f, findings in per_file.items():
            for loc, cat, detail in findings:
                print(f"  - {_display_path(f, root)}:{loc}: {cat}: {detail}")
    print("  - " + _summary(total, len(nb_files), by_cat, f"{len(nb_files)} file(s) scanned"))

    if total == 0:
        print(f"clean  (0 of {len(nb_files)} files)")
    else:
        prefix = "ERROR" if (strict and total) else "WARNING"
        print(
            f"{prefix}: {len(per_file)} file(s) with issues  "
            f"({len(per_file)} of {len(nb_files)} files)"
        )
    return 1 if (strict and total) else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
